// A synthetic corpus of ChatGPT titles from seven kinds of people, with the
// category a person would file each one under. Written before the classifier
// was tuned, so it measures the rules rather than restating them.
//
// `expected` is "primary" or "primary/subcategory". Where a title honestly
// reads two ways, `also` lists the other acceptable answers. A subcategory is
// only checked when one is given.

export interface LabelledTitle {
  title: string
  expected: string
  also?: string[]
}

export type PersonaId = 'engineer' | 'student' | 'parent' | 'jobSeeker' | 'creator' | 'business' | 'mixed'

const t = (title: string, expected: string, ...also: string[]): LabelledTitle => ({ title, expected, ...(also.length ? { also } : {}) })

