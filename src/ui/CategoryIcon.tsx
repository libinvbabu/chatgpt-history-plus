export function Glyph({ name, size = 14, ...p }: SVGProps<SVGSVGElement> & { name: GlyphName; size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.75} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" {...p}>
      {PATHS[name]}
    </svg>
  )
}

/**
 * The icon beside a conversation: always 15px in a fixed 18px box, so titles line
 * up whichever icon a row has. The category name shows on hover.
 */
export function CategoryIcon({ conv }: { conv: { title: string; category?: string | null } }) {
  const { icon, label, primary, sub } = categoryDisplay(classificationOf(conv))
  return (
    <span className="cat" title={label} data-category={primary} data-sub={sub ?? undefined}>
      <Glyph name={icon} size={15} />
    </span>
  )
}
