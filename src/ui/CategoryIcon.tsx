/**
 * The icon beside a conversation: always 15px in a fixed 18px box, so titles line
 * up whichever icon a row has. The category name shows on hover.
 */
export function CategoryIcon({ conv }: { conv: { title: string; category?: string | null } }) {
  const { icon, label, filter } = categoryDisplay(categoryFor(conv))
  return (
    <span className="cat" title={label} data-category={filter}>
      <Glyph name={icon} size={15} />
    </span>
  )
}
